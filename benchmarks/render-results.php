function n(float|int|null $v, int $d = 0): string
{
    return $v === null ? '-' : number_format((float) $v, $d, '.', ',');
}

function st(array $s, int $d = 0): string
{
    return isset($s['median']) ? n($s['median'], $d) : '-';
}

function range_(array $s, int $d = 0): string
{
    if (! isset($s['median'])) {
        return '-';
    }
    $txt = n($s['median'], $d).' ('.n($s['min'], $d).'-'.n($s['max'], $d).')';

    return ($s['spread_pct'] ?? 0) > 15 ? $txt.' **spread '.n($s['spread_pct'], 0).'%**' : $txt;
}

function mib(float $bytes): string
{
    return n($bytes / 1048576, 2);
}

function cpuPerReq(array $c): ?float
{
    $v = [];
    foreach ($c['runs'] as $r) {
        if (($r['requests'] ?? 0) > 0) {
            $v[] = $r['cpu_s'] / $r['requests'] * 1000;
        }
    }
    if ($v === []) {
        return null;
    }
    sort($v);

    return $v[intdiv(count($v), 2)];
}

function md(array $head, array $rows): string
{
    $out = '| '.implode(' | ', $head)." |\n|".str_repeat('---|', count($head))."\n";
    foreach ($rows as $r) {
        $out .= '| '.implode(' | ', $r)." |\n";
    }

    return $out."\n";
}

function caseTable(array $cases, bool $latency = true): string
{
    $head = ['case', 'requests per run', 'req/s: median (min-max)', ...($latency ? ['p50 ms', 'p95 ms', 'p99 ms', 'max ms'] : []), 'peak MiB over start', 'growth KiB (raw / after gc)', 'cpu ms/req', 'transport errors', 'connections opened (this run / since server reset)', 'max concurrent streams (server)'];
    $rows = [];
    foreach ($cases as $c) {
        $s = $c['summary'];
        $last = $c['runs'][count($c['runs']) - 1];
        $row = [
            $c['label'],
            n($c['runs'][0]['requests']),
            range_($s['rps']),
        ];
        if ($latency) {
            array_push($row, st($s['p50_ms'] ?? [], 1), st($s['p95_ms'] ?? [], 1), st($s['p99_ms'] ?? [], 1), st($s['max_ms'] ?? [], 1));
        }
        array_push(
            $row,
            st($s['peak_over_start_mib'], 2),
            n(($s['mem_growth_bytes']['median'] ?? 0) / 1024, 0).' / '.n(($s['mem_growth_after_gc_bytes']['median'] ?? 0) / 1024, 0),
            n(cpuPerReq($c), 3),
            st($s['transport_errors']),
            st($s['connections_opened']).' / '.n($last['server']['connections_total_since_reset']),
            st($s['max_concurrent_streams']),
        );
        $rows[] = $row;
    }

    return md($head, $rows);
}

